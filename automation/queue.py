#!/usr/bin/env python3
"""
Task-queue CLI for the CASCADIA overnight runner. One small module instead of
four scripts: pick/update/fail/summary are all tiny operations on the same
JSON file.
ponytail: this is bespoke automation tooling, not a CASCADIA product feature
-- plain stdlib json, no queue library, no retry framework.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
QUEUE_PATH = ROOT / "execution" / "TASK_QUEUE.json"


def load():
    return json.loads(QUEUE_PATH.read_text())


def save(data):
    QUEUE_PATH.write_text(json.dumps(data, indent=2) + "\n")


def deps_satisfied(task, by_id):
    return all(by_id[d]["status"] == "done" for d in task.get("depends_on", []))


def cmd_pick():
    data = load()
    by_id = {t["id"]: t for t in data["tasks"]}
    for t in data["tasks"]:
        if t["status"] == "pending" and deps_satisfied(t, by_id):
            print(json.dumps(t))
            return
    # nothing eligible: either all done, or the next pending task's deps include
    # something blocked/failed -- either way, correctly report "nothing to do"
    print("null")


def cmd_update_status(task_id, status):
    data = load()
    for t in data["tasks"]:
        if t["id"] == task_id:
            t["status"] = status
            save(data)
            return
    raise SystemExit(f"no such task: {task_id}")


def cmd_record_failure(task_id, reason, max_retries):
    data = load()
    for t in data["tasks"]:
        if t["id"] == task_id:
            t.setdefault("failures", []).append(reason)
            if len(t["failures"]) >= int(max_retries):
                t["status"] = "blocked"
            else:
                t["status"] = "pending"  # retry on next fire
            save(data)
            print(t["status"])
            return
    raise SystemExit(f"no such task: {task_id}")


def cmd_write_summary():
    data = load()
    tasks = data["tasks"]
    done = [t for t in tasks if t["status"] == "done"]
    blocked = [t for t in tasks if t["status"] == "blocked"]
    pending = [t for t in tasks if t["status"] == "pending"]
    in_progress = [t for t in tasks if t["status"] == "in_progress"]

    log = subprocess.run(
        ["git", "-C", str(ROOT), "log", "--oneline", "-20"],
        capture_output=True, text=True,
    ).stdout

    lines = [
        "# Overnight Summary",
        "",
        f"Generated by automation/queue.py write-summary.",
        "",
        "## Tasks",
        "",
        f"- Done: {len(done)}/{len(tasks)} -- {', '.join(t['id'] for t in done) or '(none)'}",
        f"- Blocked: {len(blocked)} -- {', '.join(t['id'] for t in blocked) or '(none)'}",
        f"- Still pending: {len(pending)} -- {', '.join(t['id'] for t in pending) or '(none)'}",
        f"- In progress (interrupted mid-task): {len(in_progress)} -- {', '.join(t['id'] for t in in_progress) or '(none)'}",
        "",
        "## Recent commits",
        "",
        "```",
        log.strip(),
        "```",
        "",
        "## Next action",
        "",
    ]
    if blocked:
        lines.append(f"Blocked tasks need manual review: {', '.join(t['id'] for t in blocked)}. See execution/BLOCKERS.md and logs/overnight/.")
    elif pending or in_progress:
        lines.append("Re-run automation/overnight-runner.sh, or resume manually -- the queue has remaining work.")
    else:
        lines.append("All queued tasks are done. Define the next milestone's tasks in execution/TASK_QUEUE.json before the next run.")
    (ROOT / "execution" / "OVERNIGHT_SUMMARY.md").write_text("\n".join(lines) + "\n")
    print("wrote execution/OVERNIGHT_SUMMARY.md")


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "pick":
        cmd_pick()
    elif cmd == "update-status":
        cmd_update_status(sys.argv[2], sys.argv[3])
    elif cmd == "record-failure":
        cmd_record_failure(sys.argv[2], sys.argv[3], sys.argv[4])
    elif cmd == "write-summary":
        cmd_write_summary()
    else:
        raise SystemExit(f"unknown command: {cmd}")
