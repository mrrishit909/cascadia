import { createRequire } from 'node:module'
const require = createRequire('/Users/rishitmathurrishit/cascadia/package.json')
const { chromium } = require('@playwright/test')
const b = await chromium.launch(); const p = await b.newPage()

await p.goto('http://localhost:4173/')
console.log('=== Test 1: Increase load ===')
await p.getByLabel('Load bus').selectOption({ index: 1 }) // first real bus with load
await p.waitForTimeout(100)
const slider = p.locator('section:has-text("Increase load") input[type=range]')
for (let i = 0; i < 20; i++) await slider.press('ArrowRight') // 1x -> up to 6x (step 0.25, max 10)
await p.getByRole('button', { name: 'Apply load' }).click()
await p.waitForTimeout(800)
console.log('load-factor:', await p.getByTestId('load-factor').textContent())
console.log('load-mw:', await p.getByTestId('load-mw').textContent())
console.log('load-unserved:', await p.getByTestId('load-unserved').textContent())

console.log('=== Test 2: Line outage ===')
await p.goto('http://localhost:4173/')
await p.getByLabel('Line to disable').selectOption({ index: 10 })
await p.getByRole('button', { name: 'Disable line' }).click()
await p.getByRole('button', { name: 'Confirm outage' }).click()
await p.waitForTimeout(800)
console.log('outage-list:', await p.getByTestId('outage-list').textContent())
console.log('outage-islands:', await p.getByTestId('outage-islands').textContent())
console.log('outage-unserved:', await p.getByTestId('outage-unserved').textContent())

console.log('=== Test 3: Reduce generator ===')
await p.goto('http://localhost:4173/')
await p.locator('section:has-text("Reduce generator") select').first().selectOption({ index: 1 })
await p.waitForTimeout(100)
const genSlider = p.locator('section:has-text("Reduce generator") input[type=range]')
await genSlider.fill('0')
await p.getByRole('button', { name: 'Apply limit' }).click()
await p.waitForTimeout(800)
console.log('gen-unserved:', await p.getByTestId('gen-unserved').textContent().catch(() => '(testid not found, checking page text)'))
const genSection = await p.locator('section:has-text("Reduce generator")').textContent()
console.log('gen section text:', genSection)

await p.screenshot({ path: '/tmp/m4_after_interactions.png', fullPage: true })
await b.close()
